const TOKEN_RE = /^\[([^\]]+)\]$/;

export function getWechatEmojiSource(name: string): ImageSourcePropType | null {
  return WECHAT_EMOJI_SOURCES[name] ?? null;
}

export function getWechatEmojiSourceFromToken(token: string): ImageSourcePropType | null {
  const m = token.trim().match(TOKEN_RE);
  if (!m) return null;
  return getWechatEmojiSource(m[1]);
}

export function isPureWechatEmojiText(text: string): boolean {
  return getWechatEmojiSourceFromToken(text.trim()) != null;
}

export type EmojiTextSegment =
  | { kind: "text"; value: string }
  | { kind: "emoji"; name: string; source: ImageSourcePropType };

export function parseWechatEmojiText(text: string): EmojiTextSegment[] {
  const parts = text.split(/(\[[^\]]+\])/g).filter((p) => p.length > 0);
  return parts.map((part) => {
    const m = part.match(TOKEN_RE);
    if (m) {
      const source = getWechatEmojiSource(m[1]);
      if (source) return { kind: "emoji", name: m[1], source };
    }
    return { kind: "text", value: part };
  });
}