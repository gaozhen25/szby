"""账号报告合规规则分块的统一生成要求。"""

COMPLIANCE_RULES_GUIDANCE = """任务：根据 accountContext.account 中的账号定位、产品或服务、目标人群、行业和目标平台，结合 evidence 中的公开内容证据，生成与该账号强相关、可直接用于内容自检的行业敏感词清单及合规替代表达。

内容范围：
1. 同时覆盖“证据复盘风险”和“行业预防风险”。证据复盘风险来自 currentAccountEvidence 或 industryEvidence 中实际出现的表达；行业预防风险应结合行业、产品或服务、目标人群、转化目标和目标平台独立推演，即使没有公开样本或即使公开样本中暂未出现也必须覆盖，不能把爬取结果当成敏感词库的唯一来源。
2. 从以下类别筛选强相关内容：
   - 广告法极限词：绝对化用语、排他性用语、权威性用语、夸张承诺；
   - 医疗功效词：仅医疗、健康、美妆护肤、医疗美容等相关行业；
   - 金融承诺词：仅金融、投资、保险等相关行业；
   - 平台禁词：结合 accountContext.account.platforms 和 sourceMeta.platforms，识别抖音、小红书、快手、视频号、公众号等平台的引流、互动诱导或敏感表达。
3. 行业补充重点：美妆护肤关注虚假美白、抗衰、瘦身和绝对化功效；教育培训关注保过、押题、速成等效果承诺；金融理财关注保本、稳赚、高收益和诱导投资；医疗美容关注治疗、治愈、微创等医疗功效和医美引流；食品关注降三高、抗癌、未经认证的纯天然宣称；房地产关注升值、学区、稳赚等承诺。
4. 每个适用类别尽量给出 3–8 个不重复的高频风险表达；不适用的类别不得硬凑。全部 complianceRules 必须控制在 1–20 项，数量上限与分类数量冲突时优先遵守 20 项上限并覆盖风险最高、最相关的表达。
5. expression 必须是创作者可在文案中直接检索的具体词或短语，不得抄写整句样本文案，不得输出“注意广告法”“避免夸大宣传”等抽象规则名称。近义表达应合并，避免用轻微变体重复占位。

风险等级：
- high：医疗功效、金融收益或保本承诺、明确绝对化或排他性用语、明显平台引流等高风险表达；
- medium：夸张承诺、互动诱导、容易造成误解但可通过限定语修正的表达；
- low：边界模糊、依赖上下文判断的权威性或宣传性表达。

事实与依据边界：
- 只有表达确实来自 currentAccountEvidence 时，才能描述为当前账号已出现；来自行业证据时应明确为行业样本风险；推演内容必须明确为预防性风险，不得把预防性风险描述为当前账号已经违规。
- reason 应先说明类别及风险逻辑。仅在能够根据输入和通用确定性知识可靠确认时引用具体法律法规或平台规则；不确定时只说明规则类型和合规风险。不得编造法规编号、处罚结果或平台公告，也不得编造处罚金额。

输出映射：
- 顶层只输出 complianceRules，不输出账号信息、风险数量统计或合规建议等额外字段。
- 每项只包含 riskLevel、expression、reason、suggestion、platforms。
- riskLevel 只能是 high、medium、low；expression 是一个具体风险词或短语；reason 用中文包含风险类别、适用条件和风险原因；suggestion 必须是字符串，可用“、”列出 2–4 个实际可用的替代表达，不得输出数组；platforms 只列该规则适用的平台，通用规则可列账号目标平台。"""
