#!/usr/bin/env bash
# 在 Linux 服务器项目根目录执行 —— 一键完成：配置 / 登录态检查 / 验证 / systemd
# 用法:
#   ./scripts/linux_server_deploy.sh              # 完整部署（需已 uv sync + Chrome）
#   ./scripts/linux_server_deploy.sh --skip-setup # 跳过 apt/Chrome 安装（已跑过 setup.sh）
#   ./scripts/linux_server_deploy.sh --with-api   # 安装并启动 systemd API

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "${PROJECT_ROOT}"

SKIP_SETUP=0
WITH_API=0
DEPLOY_USER="${SUDO_USER:-$USER}"
VERIFY_KEYWORD="${VERIFY_KEYWORD:-测试}"

for arg in "$@"; do
  case "$arg" in
    --skip-setup) SKIP_SETUP=1 ;;
    --with-api) WITH_API=1 ;;
  esac
done

export PATH="${HOME}/.local/bin:${PATH}"

log() { echo "[deploy] $*"; }

if [[ "$(uname -s)" != "Linux" ]]; then
  echo "此脚本需在 Linux 服务器上运行；从 Mac 请用: ./scripts/deploy_from_local.sh user@host"
  exit 1
fi

if [[ "${SKIP_SETUP}" -eq 0 ]]; then
  log "步骤 1/6: 安装系统依赖 (linux_server_setup.sh)..."
  chmod +x scripts/linux_server_setup.sh
  sudo scripts/linux_server_setup.sh
else
  log "步骤 1/6: 跳过系统安装 (--skip-setup)"
  uv sync
fi

log "步骤 2/6: 写入 Linux 服务器配置 overrides..."
cat > config/linux_server_overrides.py <<'PY'
# Auto-generated by linux_server_deploy.sh — do not edit on server; re-run deploy to reset
PLATFORM = "xhs"
LOGIN_TYPE = "cookie"
HEADLESS = True
CDP_HEADLESS = True
ENABLE_CDP_MODE = True
SAVE_LOGIN_STATE = True
SAVE_DATA_OPTION = "json"
CUSTOM_BROWSER_PATH = "/usr/bin/google-chrome-stable"
MAX_CONCURRENCY_NUM = 1
AUTO_CLOSE_BROWSER = True
PY

if ! grep -q "linux_server_overrides" config/base_config.py 2>/dev/null; then
  log "步骤 2b: 在 base_config.py 末尾挂载 overrides..."
  cat >> config/base_config.py <<'PY'

# Linux server overrides (generated by deploy script)
try:
    from .linux_server_overrides import *  # noqa: F403
except ImportError:
    pass
PY
fi

log "步骤 3/6: 检查登录态..."
LOGIN_OK=0
if [[ -d browser_data/cdp_xhs_user_data_dir ]] || [[ -f browser_data/cdp_xhs_storage_state.json ]]; then
  log "  发现 browser_data 登录目录"
  LOGIN_OK=1
fi
if [[ -n "${XHS_COOKIES:-}" ]]; then
  log "  环境变量 XHS_COOKIES 已设置"
  LOGIN_OK=1
fi
if [[ "${LOGIN_OK}" -eq 0 ]]; then
  log "  警告: 未检测到登录态。请任选其一:"
  log "    - 上传 browser_data_login.tar.gz 到项目根目录后执行: tar xzf browser_data_login.tar.gz"
  log "    - 或设置: export XHS_COOKIES='web_session=...; a1=...;'"
  log "  继续执行验证可能因未登录而失败。"
fi

if [[ -f browser_data_login.tar.gz ]]; then
  log "  解压 browser_data_login.tar.gz ..."
  tar xzf browser_data_login.tar.gz
fi

chmod +x mc 2>/dev/null || true

log "步骤 4/6: 运行单元测试 (SDK, 无需浏览器)..."
uv run pytest tests/test_sdk_extractor_api_dict.py tests/test_sdk_extractor.py tests/test_sdk_json_export.py -q

log "步骤 5/6: 爬取验证 (keyword=${VERIFY_KEYWORD})..."
CRAWL_CMD=(uv run ./mc search "${VERIFY_KEYWORD}" -n 3)
if [[ -n "${XHS_COOKIES:-}" ]]; then
  CRAWL_CMD=(uv run python -c "
from sdk import keyword_ex
r = keyword_ex('xhs', '${VERIFY_KEYWORD}', max_notes_count=3, login_type='cookie', cookies='''${XHS_COOKIES}''', headless=True)
print('code:', r['code'])
print('note_count:', r['data']['summary'].get('note_count'))
assert r['code'] == 0, r
")
fi

if ! "${CRAWL_CMD[@]}"; then
  log "  爬取验证失败 — 多为未登录或 Chrome 问题，见 docs/linux_server_deploy.md 第 11 节"
  exit 1
fi

log "步骤 6/6: API 服务..."
if [[ "${WITH_API}" -eq 1 ]]; then
  SERVICE=/etc/systemd/system/mediacrawler-api.service
  sed "s|User=deploy|User=${DEPLOY_USER}|g; s|/opt/MediaCrawler|${PROJECT_ROOT}|g; s|/home/deploy|${HOME}|g" \
    deploy/mediacrawler-api.service.example | sudo tee "${SERVICE}" >/dev/null
  sudo systemctl daemon-reload
  sudo systemctl enable mediacrawler-api
  sudo systemctl restart mediacrawler-api
  sleep 2
  curl -sf "http://127.0.0.1:8080/api/health" && log "  API 健康检查 OK" || log "  API 未响应，请 journalctl -u mediacrawler-api"
else
  log "  跳过 systemd（加 --with-api 启用）。手动启动:"
  log "    uv run uvicorn api.main:app --host 127.0.0.1 --port 8080"
fi

log "=========================================="
log "  Linux 部署流程完成"
log "  项目: ${PROJECT_ROOT}"
log "  数据: ${PROJECT_ROOT}/data/xhs/json/"
log "  文档: docs/linux_server_deploy.md"
log "=========================================="
